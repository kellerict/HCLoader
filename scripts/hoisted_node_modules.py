"""bgutil provider: hoisted `node_modules` without links (portable/relocatable), plus a check.

Deno's default `deno install` layout is pnpm-like ("isolated"): `node_modules/<pkg>` is a link to
`node_modules/.deno/<pkg>@<v>/node_modules/<pkg>`, and the dependencies of a package are sibling
links in `.deno/<pkg>@<v>/node_modules/`. On Windows these links are junctions with absolute
targets. With a `package.json`, `deno run` resolves npm packages like Node (manual mode), so the
link targets matter: copying the top-level links (old `materialize_links.py` approach) moved the
referrer out of `.deno` and transitive dependencies were no longer found after moving the folder.

Deno 2.8+ can install npm's hoisted layout instead (`--node-modules-linker=hoisted`, requires
`nodeModulesDir: "manual"`): real files only, the most used version at the top, conflicting
versions nested under the dependent. That folder can be zipped and moved (docs/decisions.md).

Usage (standard library only, runs in the embedded Python):
  python hoisted_node_modules.py configure <server>   -> deno.json: manual + hoisted
  python hoisted_node_modules.py check <server> [--native canvas ...]
      -> exit 0 if every dependency in deno.lock resolves with Node's walk-up algorithm to the
         locked version, no link exists below node_modules and native addons are built.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

DENO_SETTINGS = {"nodeModulesDir": "manual", "nodeModulesLinker": "hoisted"}


# --------------------------------------------------------------------------- deno.json


def configure(server: Path) -> bool:
    """Set nodeModulesDir=manual + nodeModulesLinker=hoisted in `server/deno.json` (other keys
    kept). Returns True if the file changed."""
    path = Path(server) / "deno.json"
    data: dict = {}
    if path.is_file():
        data = json.loads(path.read_text(encoding="utf-8-sig"))
        if not isinstance(data, dict):
            raise ValueError(f"{path}: JSON-Objekt erwartet")
    if all(data.get(k) == v for k, v in DENO_SETTINGS.items()):
        return False
    data.update(DENO_SETTINGS)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return True


# --------------------------------------------------------------------------- deno.lock


def split_key(key: str) -> tuple[str, str | None]:
    """'@scope/name@1.2.3_peer@4' -> ('@scope/name', '1.2.3'); 'name' -> ('name', None)."""
    at = key.find("@", 1)
    if at < 0:
        return key, None
    return key[:at], key[at + 1 :].split("_", 1)[0]


class Lock:
    """The npm part of a deno.lock (v4/v5): versions per name and dependencies per version."""

    def __init__(self, data: dict) -> None:
        self.versions: dict[str, set[str]] = {}
        # (name, version) -> {dep name: (allowed versions, optional)}; peer variants are merged
        self.deps: dict[tuple[str, str], dict[str, tuple[set[str], bool]]] = {}
        npm = data.get("npm") or {}
        for key in npm:
            name, version = split_key(key)
            if version:
                self.versions.setdefault(name, set()).add(version)
        for key, info in npm.items():
            name, version = split_key(key)
            if not version or not isinstance(info, dict):
                continue
            optional = set(info.get("optionalPeers") or ())
            entries = [(d, False) for d in info.get("dependencies") or ()]
            entries += [(d, True) for d in info.get("optionalDependencies") or ()]
            merged = self.deps.setdefault((name, version), {})
            for dep, is_opt in entries:
                dname, dver = split_key(dep)
                allowed = {dver} if dver else set(self.versions.get(dname, ()))
                old_allowed, old_opt = merged.get(dname, (set(), True))
                merged[dname] = (old_allowed | allowed, old_opt and (is_opt or dname in optional))
        self.roots: dict[str, set[str]] = {}
        specifiers = data.get("specifiers") or {}
        pkg_json = (data.get("workspace") or {}).get("packageJson") or {}
        for spec in list(pkg_json.get("dependencies") or ()) + list(
            pkg_json.get("devDependencies") or ()
        ):
            resolved = specifiers.get(spec)
            if not resolved or not spec.startswith("npm:"):
                continue
            name, _ = split_key(spec[4:])
            self.roots.setdefault(name, set()).add(resolved.split("_", 1)[0])

    @classmethod
    def load(cls, path: Path) -> Lock:
        return cls(json.loads(Path(path).read_text(encoding="utf-8")))


# --------------------------------------------------------------------------- node_modules


def is_link(path: Path) -> bool:
    if path.is_symlink():
        return True
    isjunction = getattr(os.path, "isjunction", None)  # Python 3.12+
    return bool(isjunction and isjunction(path))


def find_links(folder: Path) -> list[Path]:
    """All symlinks/junctions below `folder` (links are not followed)."""
    found: list[Path] = []
    stack = [Path(folder)]
    while stack:
        current = stack.pop()
        with os.scandir(current) as it:
            for entry in it:
                path = Path(entry.path)
                if is_link(path):
                    found.append(path)
                elif entry.is_dir(follow_symlinks=False):
                    stack.append(path)
    return sorted(found)


def _read_manifest(pkg_dir: Path) -> tuple[str, str] | None:
    try:
        data = json.loads((pkg_dir / "package.json").read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return None
    if not isinstance(data, dict):
        return None
    return str(data.get("name") or ""), str(data.get("version") or "")


def installed_packages(node_modules: Path) -> list[Path]:
    """Package folders in `node_modules` and, recursively, in their nested node_modules
    (hidden entries like .bin/.deno skipped)."""
    result: list[Path] = []
    stack = [Path(node_modules)]
    while stack:
        nm = stack.pop()
        if not nm.is_dir() or is_link(nm):
            continue
        for entry in sorted(nm.iterdir()):
            if entry.name.startswith(".") or is_link(entry) or not entry.is_dir():
                continue
            candidates = sorted(entry.iterdir()) if entry.name.startswith("@") else [entry]
            for pkg in candidates:
                if is_link(pkg) or not (pkg / "package.json").is_file():
                    continue
                result.append(pkg)
                stack.append(pkg / "node_modules")
    return result


def resolve(name: str, from_dir: Path, root: Path) -> Path | None:
    """Node's walk-up: <dir>/node_modules/<name> for `from_dir` and its parents up to `root`
    (folders named node_modules themselves are skipped)."""
    current = Path(from_dir)
    root = Path(root)
    while True:
        if current.name != "node_modules":
            candidate = current / "node_modules" / name
            if (candidate / "package.json").is_file():
                return candidate
        if current == root or current.parent == current:
            return None
        current = current.parent


def check(server: Path, native: tuple[str, ...] = ()) -> tuple[list[str], int]:
    """Problems of `server/node_modules` (empty list = fine) and the number of checked packages."""
    server = Path(server)
    nm = server / "node_modules"
    lock_path = server / "deno.lock"
    if not nm.is_dir():
        return [f"node_modules fehlt: {nm}"], 0
    if not lock_path.is_file():
        return [f"deno.lock fehlt: {lock_path}"], 0
    problems = [f"Link (nicht verschiebbar): {p}" for p in find_links(nm)]
    lock = Lock.load(lock_path)

    for name, versions in sorted(lock.roots.items()):
        found = resolve(name, server, server)
        manifest = _read_manifest(found) if found else None
        if not manifest:
            problems.append(f"Direkte Abhaengigkeit fehlt: {name}")
        elif manifest[1] not in versions:
            problems.append(f"{name}: Version {manifest[1]} statt {'/'.join(sorted(versions))}")

    packages = installed_packages(nm)
    for pkg in packages:
        manifest = _read_manifest(pkg)
        if not manifest:
            continue
        deps = lock.deps.get(manifest)
        if deps is None:
            continue  # not in the lock (alias, bundled): nothing to compare against
        for dep_name, (allowed, optional) in sorted(deps.items()):
            found = resolve(dep_name, pkg, server)
            got = _read_manifest(found) if found else None
            rel = pkg.relative_to(server).as_posix()
            if got is None:
                if not optional:
                    problems.append(f"{rel}: findet {dep_name} nicht")
            elif allowed and got[1] not in allowed:
                want = "/".join(sorted(allowed))
                problems.append(f"{rel}: {dep_name} {got[1]} statt {want}")

    for name in native:
        found = resolve(name, server, server)
        release = found / "build" / "Release" if found else None
        if not release or not any(release.glob("*.node")):
            problems.append(f"Native Erweiterung fehlt: {name}/build/Release/*.node")
    return problems, len(packages)


# --------------------------------------------------------------------------- CLI


def long_path(path: Path) -> Path:
    """Windows: extended-length form (\\\\?\\C:\\...), deep nested node_modules may exceed
    MAX_PATH (260). No-op elsewhere (same as materialize_links.py)."""
    if os.name != "nt":
        return path
    text = os.path.abspath(str(path))
    if text.startswith("\\\\?\\"):
        return Path(text)
    if text.startswith("\\\\"):  # UNC share
        return Path("\\\\?\\UNC\\" + text[2:])
    return Path("\\\\?\\" + text)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="hoisted_node_modules.py")
    sub = parser.add_subparsers(dest="cmd", required=True)
    p_conf = sub.add_parser("configure")
    p_conf.add_argument("server")
    p_check = sub.add_parser("check")
    p_check.add_argument("server")
    p_check.add_argument("--native", action="append", default=[])
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        return int(exc.code or 0) or 2
    server = long_path(Path(args.server))
    if not server.is_dir():
        print(f"Ordner fehlt: {server}", file=sys.stderr)
        return 2
    if args.cmd == "configure":
        changed = configure(server)
        print(f"    deno.json: {'angepasst' if changed else 'unveraendert'} (manual + hoisted)")
        return 0
    problems, count = check(server, tuple(args.native))
    if problems:
        for line in problems[:40]:
            print(f"    FEHLER {line}", file=sys.stderr)
        if len(problems) > 40:
            print(f"    ... und {len(problems) - 40} weitere", file=sys.stderr)
        return 1
    print(f"    node_modules ok: {count} Pakete, keine Links, Abhaengigkeiten aufloesbar")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
